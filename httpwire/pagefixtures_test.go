// The page fixtures are httpserver.PageMatcher's answers over fixed page
// tables. The TS router's test holds its match to them, so a ServeMux rule
// the router misreads fails there rather than in an app.
const (
	pagesDir        = "web/testdata/pages"
	pagesModuleFile = "web/src/testing/page-fixtures.ts"
	pagesRegen      = "regenerate with UPDATE_GOLDEN=1 go test . -run TestPageFixtures in httpwire, then run the TS half's page fixture test"
)

type pageSet struct {
	name      string
	apiPrefix string
	pages     []httpserver.Page
	paths     []string
}

type pageCase struct {
	Params     map[string]string `json:"params,omitzero"`
	Path       string            `json:"path"`
	Name       string            `json:"name,omitempty"`
	Redirect   string            `json:"redirect,omitempty"`
	ServerOnly bool              `json:"serverOnly,omitempty"`
}

type pageFixture struct {
	Pages     map[string]string `json:"pages"`
	APIPrefix string            `json:"apiPrefix"`
	Cases     []pageCase        `json:"cases"`
}

