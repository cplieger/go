// dotSegment reports a path segment of ".", ".." or a %2e spelling of either,
// which a browser's URL parser removes before the router reads the path
// (WHATWG URL, the path state's single-dot and double-dot segments).
func dotSegment(target string) bool {
	p, _, _ := strings.Cut(target, "?")
	for seg := range strings.SplitSeq(p, "/") {
		if s := strings.ReplaceAll(strings.ToLower(seg), "%2e", "."); s == "." || s == ".." {
			return true
		}
	}
	return false
}

func matchedFixture(t *testing.T, tb pageSet) pageFixture {
	t.Helper()
	m, err := httpserver.NewPageMatcher(tb.pages, tb.apiPrefix)
	if err != nil {
		t.Fatalf("%s: %v", tb.name, err)
	}
	f := pageFixture{Pages: map[string]string{}, APIPrefix: tb.apiPrefix}
	for _, p := range tb.pages {
		f.Pages[p.Name] = p.Pattern
	}
	seen := map[string]bool{}
	for _, p := range tb.paths {
		if seen[p] {
			t.Fatalf("%s: path %q listed twice", tb.name, p)
		}
		seen[p] = true
		c := pageCase{Path: p, ServerOnly: dotSegment(p)}
		if got, ok := m.Match(p); ok {
			c.Name, c.Params, c.Redirect = got.Name, got.Params, got.Redirect
		}
		f.Cases = append(f.Cases, c)
	}
	return f
}

func encodePageFixture(t *testing.T, f pageFixture) []byte {
	t.Helper()
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(f); err != nil {
		t.Fatal(err)
	}
	return b.Bytes()
}

// pagesModule is the PAGE_FIXTURES module @cplieger/httpwire/testing exports,
// since the package ships src/ and not testdata/. It is written as prettier
// writes it, so prettier --check leaves the file alone.
func pagesModule(t *testing.T, fixtures map[string]pageFixture) []byte {
	t.Helper()
	var b strings.Builder
	b.WriteString("// Code generated by httpwire's TestPageFixtures from testdata/pages; DO NOT EDIT.\n\n" +
		"import type { PageFixture } from \"./pages.js\";\n\n" +
		"/** Page tables with the answer `httpserver.PageMatcher` gives for each path. */\n" +
		"export const PAGE_FIXTURES: readonly PageFixture[] = [\n")
	for _, name := range slices.Sorted(maps.Keys(fixtures)) {
		f := fixtures[name]
		fmt.Fprintf(&b, "  {\n    name: %s,\n    pages: {\n", jsString(t, name))
		for _, page := range slices.Sorted(maps.Keys(f.Pages)) {
			fmt.Fprintf(&b, "      %s: %s,\n", page, jsString(t, f.Pages[page]))
		}
		fmt.Fprintf(&b, "    },\n    apiPrefix: %s,\n    cases: [\n", jsString(t, f.APIPrefix))
		for _, c := range f.Cases {
			fmt.Fprintf(&b, "      {\n        path: %s,\n", jsString(t, c.Path))
			if c.Name != "" {
				fmt.Fprintf(&b, "        name: %s,\n", jsString(t, c.Name))
			}
			if c.Params != nil {
				if len(c.Params) == 0 {
					b.WriteString("        params: {},\n")
				} else {
					b.WriteString("        params: {\n")
					for _, k := range slices.Sorted(maps.Keys(c.Params)) {
						fmt.Fprintf(&b, "          %s: %s,\n", k, jsString(t, c.Params[k]))
					}
					b.WriteString("        },\n")
				}
			}
			if c.Redirect != "" {
				fmt.Fprintf(&b, "        redirect: %s,\n", jsString(t, c.Redirect))
			}
			if c.ServerOnly {
				b.WriteString("        serverOnly: true,\n")
			}
			b.WriteString("      },\n")
		}
		b.WriteString("    ],\n  },\n")
	}
	b.WriteString("];\n")
	return []byte(b.String())
}

func jsString(t *testing.T, s string) string {
	t.Helper()
	if strings.ContainsAny(s, `"\`) {
		t.Fatalf("%q needs escaping the page fixture writer does not do", s)
	}
	return `"` + s + `"`
}

func TestPageFixtures(t *testing.T) {
	want := map[string]pageFixture{}
	for _, tb := range pageSets() {
		want[tb.name] = matchedFixture(t, tb)
	}

	if os.Getenv("UPDATE_GOLDEN") == "1" {
		if err := os.RemoveAll(pagesDir); err != nil {
			t.Fatal(err)
		}
		if err := os.MkdirAll(pagesDir, 0o755); err != nil {
			t.Fatal(err)
		}
		for name, f := range want {
			if err := os.WriteFile(filepath.Join(pagesDir, name+".json"), encodePageFixture(t, f), 0o644); err != nil {
				t.Fatal(err)
			}
		}
		if err := os.WriteFile(pagesModuleFile, pagesModule(t, want), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if got, err := os.ReadFile(pagesModuleFile); err != nil || !bytes.Equal(got, pagesModule(t, want)) {
		t.Errorf("%s is missing or stale (%v); %s", pagesModuleFile, err, pagesRegen)
	}

	files, err := filepath.Glob(filepath.Join(pagesDir, "*.json"))
	if err != nil || len(files) == 0 {
		t.Fatalf("no fixtures under %s (%v); %s", pagesDir, err, pagesRegen)
	}
	for _, path := range files {
		name := strings.TrimSuffix(filepath.Base(path), ".json")
		got, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		f, ok := want[name]
		if !ok {
			t.Errorf("%s has no table in this test; %s", path, pagesRegen)
			continue
		}
		if !bytes.Equal(got, encodePageFixture(t, f)) {
			t.Errorf("%s differs from PageMatcher's answers; %s", path, pagesRegen)
		}
	}
	for name := range want {
		if _, err := os.Stat(filepath.Join(pagesDir, name+".json")); errors.Is(err, fs.ErrNotExist) {
			t.Errorf("%s.json is missing; %s", name, pagesRegen)
		}
	}
}

func readPageFixture(t *testing.T, name string) map[string]pageCase {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(pagesDir, name+".json"))
	if err != nil {
		t.Fatalf("%v; %s", err, pagesRegen)
	}
	var f pageFixture
	if err := json.Unmarshal(b, &f); err != nil {
		t.Fatal(err)
	}
	out := make(map[string]pageCase, len(f.Cases))
	for _, c := range f.Cases {
		out[c.Path] = c
	}
	return out
}

// The committed answers hold ServeMux's documented rules (net/http ServeMux:
// wildcards decoded after matching, cleaned and subtree redirects keeping the
// query), so re-recording a matcher that broke one still fails.
func TestPageFixturesHoldServeMuxRules(t *testing.T) {
	page := func(name string, params map[string]string) pageCase {
		return pageCase{Name: name, Params: params}
	}
	redirect := func(to string) pageCase { return pageCase{Redirect: to} }
	none := pageCase{}
	tests := []struct {
		want  pageCase
		table string
		path  string
	}{
		{table: "library", path: "/library", want: page("library", map[string]string{})},
		{table: "library", path: "/", want: page("home", map[string]string{})},
		{table: "library", path: "/docs", want: redirect("/docs/")},
		{table: "library", path: "/docs?q=1", want: redirect("/docs/?q=1")},
		{table: "library", path: "/docs/x", want: page("docs", map[string]string{})},
		{table: "library", path: "/settings", want: redirect("/settings/")},
		{table: "library", path: "/settings/a/b", want: page("settings", map[string]string{"part": "a/b"})},
		{table: "library", path: "/settings/a%2Fb/c", want: page("settings", map[string]string{"part": "a/b/c"})},
		{table: "library", path: "/library/a%2Fb", want: page("item", map[string]string{"id": "a/b"})},
		{table: "library", path: "/library/%C3%A9", want: page("item", map[string]string{"id": "é"})},
		{table: "library", path: "/library/a%20b", want: page("item", map[string]string{"id": "a b"})},
		{table: "library", path: "/library/x/../a?q=1", want: redirect("/library/a?q=1")},
		{table: "library", path: "//library", want: redirect("/library")},
		{table: "library", path: "//library?q=1", want: redirect("/library?q=1")},
		{table: "library", path: "/library//a", want: redirect("/library/a")},
		{table: "library", path: "/library/%2e%2e", want: page("item", map[string]string{"id": ".."})},
		{table: "library", path: "/nope", want: none},
		{table: "library", path: "/api", want: none},
		{table: "library", path: "/api/x", want: none},
		{table: "library", path: "/api/../library", want: none},
		{table: "precedence", path: "/files/new", want: page("fresh", map[string]string{})},
		{table: "precedence", path: "/files/a", want: page("file", map[string]string{"name": "a"})},
		{table: "precedence", path: "/files/a/b", want: page("tree", map[string]string{"rest": "a/b"})},
		{table: "precedence", path: "/files", want: redirect("/files/")},
		{table: "precedence", path: "/a/x/b", want: page("pair", map[string]string{"x": "x"})},
		{table: "precedence", path: "/a/x/c", want: none},
		{table: "catchall", path: "/anything/at/all", want: page("app", map[string]string{})},
		{table: "catchall", path: "/about", want: page("about", map[string]string{})},
		{table: "catchall", path: "/api/v1/x", want: none},
		{table: "catchall", path: "/api/v1", want: none},
	}
	fixtures := map[string]map[string]pageCase{}
	for _, tb := range pageSets() {
		fixtures[tb.name] = readPageFixture(t, tb.name)
	}
	for _, tt := range tests {
		t.Run(tt.table+" "+strings.ReplaceAll(tt.path, "/", "|"), func(t *testing.T) {
			got, ok := fixtures[tt.table][tt.path]
			if !ok {
				t.Fatalf("no case for %q in %s.json", tt.path, tt.table)
			}
			if got.Name != tt.want.Name || got.Redirect != tt.want.Redirect || !maps.Equal(got.Params, tt.want.Params) ||
				(got.Params == nil) != (tt.want.Params == nil) {
				t.Errorf("%q answers %+v; want %+v", tt.path, got, tt.want)
			}
		})
	}
	if lib := fixtures["library"]["/library/"]; lib.Name == "library" {
		t.Errorf("/library/ answers the exact page /library: %+v", lib)
	}
}

func TestPageFixturesMarkServerOnlyExactlyOnDotSegments(t *testing.T) {
	dots := map[string]bool{
		"/library/x/../a": true, "/library/x/../a?q=1": true, "/library/./a": true, "/library/.": true,
		"/library/%2e%2e": true, "/library/%2E%2e": true, "/library/.%2e": true,
		"/settings/a/../b": true, "/api/../library": true, "/x/../about": true,
	}
	for _, tb := range pageSets() {
		for path, c := range readPageFixture(t, tb.name) {
			if c.ServerOnly != dots[path] {
				t.Errorf("%s %q: serverOnly %v; want %v", tb.name, path, c.ServerOnly, dots[path])
			}
		}
	}
}
