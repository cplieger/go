package webbundle

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"github.com/cplieger/go/httpserver/v2"
)

// maxCasesPerPage bounds one pattern's share of the page corpus.
const maxCasesPerPage = 32

// RenderPages returns the TypeScript page table for pages and apiPrefix:
// PAGES, each page's name to its pattern in pages' order, and API_PREFIX.
// It refuses what httpserver.NewPageMatcher refuses.
func RenderPages(pages []httpserver.Page, apiPrefix string) ([]byte, error) {
	if _, err := matcher(pages, apiPrefix); err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by webbundle. DO NOT EDIT.\n\nexport const PAGES = {\n")
	for _, p := range pages {
		fmt.Fprintf(&b, "  %s: %s,\n", p.Name, jsString(p.Pattern))
	}
	fmt.Fprintf(&b, "} as const;\nexport const API_PREFIX = %s;\n", jsString(apiPrefix))
	return b.Bytes(), nil
}

func matcher(pages []httpserver.Page, apiPrefix string) (*httpserver.PageMatcher, error) {
	for _, p := range pages {
		// An object literal's __proto__ key sets the prototype, so PAGES
		// would not hold it.
		if p.Name == "__proto__" {
			return nil, errors.New("webbundle: page name __proto__ is no key of the TypeScript page table")
		}
	}
	m, err := httpserver.NewPageMatcher(pages, apiPrefix)
	if err != nil {
		return nil, fmt.Errorf("webbundle: %w", err)
	}
	return m, nil
}

// jsString is s as a string literal JSON and TypeScript both read.
func jsString(s string) string {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	_ = enc.Encode(s) // a string always encodes
	return strings.TrimSuffix(b.String(), "\n")
}

// pageCase is one page corpus case: a page with its params, a redirect, or
// neither (no page).
type pageCase struct {
	Params     map[string]string `json:"params,omitzero"`
	Path       string            `json:"path"`
	Name       string            `json:"name,omitempty"`
	Redirect   string            `json:"redirect,omitempty"`
	ServerOnly bool              `json:"serverOnly,omitempty"`
}

// RenderPageCorpus returns the page corpus for pages and apiPrefix: a JSON
// array of httpserver.PageMatcher's answers for each pattern's sample path
// and its edge cases, then "/", an unknown path, apiPrefix and a path under
// it. A case whose path holds a dot segment, which a browser's URL parser
// removes before the router reads it, carries serverOnly. It refuses what
// RenderPages refuses.
func RenderPageCorpus(pages []httpserver.Page, apiPrefix string) ([]byte, error) {
	m, err := matcher(pages, apiPrefix)
	if err != nil {
		return nil, err
	}
	var paths []string
	for _, p := range pages {
		cases := patternCases(p.Pattern)
		paths = append(paths, cases[:min(len(cases), maxCasesPerPage)]...)
	}
	paths = append(paths, "/", "/no-such-page", apiPrefix, apiPrefix+"/x")
	seen := map[string]bool{}
	corpus := make([]pageCase, 0, len(paths))
	for _, p := range paths {
		if seen[p] {
			continue
		}
		seen[p] = true
		c := pageCase{Path: p, ServerOnly: dotSegment(p)}
		if got, ok := m.Match(p); ok {
			c.Name, c.Params, c.Redirect = got.Name, got.Params, got.Redirect
		}
		corpus = append(corpus, c)
	}
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(corpus); err != nil {
		return nil, fmt.Errorf("webbundle: page corpus: %w", err)
	}
	return b.Bytes(), nil
}

// patternCases is a pattern's sample path (each {x} filled with "a", each
// {x...} with "a/b") and its edge cases, in a fixed order.
func patternCases(pattern string) []string {
	segs := strings.Split(pattern, "/")
	var wild []int
	for i, s := range segs {
		switch {
		case s == "{$}":
			segs[i] = ""
		case strings.HasSuffix(s, "...}"):
			segs[i] = "a/b"
			wild = append(wild, i)
		case strings.HasPrefix(s, "{"):
			segs[i] = "a"
			wild = append(wild, i)
		}
	}
	with := func(i int, v string) string {
		s := append([]string(nil), segs...)
		s[i] = v
		return strings.Join(s, "/")
	}
	sample := strings.Join(segs, "/")
	toggled := strings.TrimSuffix(sample, "/")
	switch toggled {
	case sample:
		toggled += "/"
	case "":
		toggled = "/"
	}
	encodedDots := strings.TrimSuffix(sample, "/") + "/%2e%2e"
	if len(wild) > 0 {
		encodedDots = with(wild[0], "%2e%2e")
	}
	cases := make([]string, 0, 8+3*len(wild))
	cases = append(cases,
		sample,
		toggled,
		"/."+sample,
		"/x/.."+sample,
		encodedDots,
		"/"+sample,
		sample+"?q=1",
		"/"+sample+"?q=1",
	)
	for _, i := range wild {
		for _, v := range []string{"a%2Fb", "%C3%A9", "a%20b"} {
			cases = append(cases, with(i, v))
		}
	}
	return cases
}

// dotSegment reports whether target's path holds a "." or ".." segment in
// any spelling (%2e in either case) a browser's URL parser removes.
func dotSegment(target string) bool {
	p, _, _ := strings.Cut(target, "?")
	for seg := range strings.SplitSeq(p, "/") {
		if s := strings.ReplaceAll(strings.ToLower(seg), "%2e", "."); s == "." || s == ".." {
			return true
		}
	}
	return false
}

// checkPageFiles refuses a page table or corpus under Src that differs from
// what Pages and APIPrefix render.
func (b *build) checkPageFiles() error {
	table, err := RenderPages(b.pages, b.apiPrefix)
	if err != nil {
		return err
	}
	corpus, err := RenderPageCorpus(b.pages, b.apiPrefix)
	if err != nil {
		return err
	}
	for _, f := range []struct {
		name string
		want []byte
	}{{b.pagesFile, table}, {b.corpusFile, corpus}} {
		got, err := os.ReadFile(filepath.Join(b.src, filepath.FromSlash(f.name)))
		switch {
		case errors.Is(err, fs.ErrNotExist):
			return fmt.Errorf("webbundle: %s is missing under Src; run go generate", f.name)
		case err != nil:
			return fmt.Errorf("webbundle: %s: %w", f.name, err)
		case !bytes.Equal(got, f.want):
			return fmt.Errorf("webbundle: %s is stale for Config.Pages and Config.APIPrefix; run go generate", f.name)
		}
	}
	return nil
}
