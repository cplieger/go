const (
	roleDeadsetEdges = "deadset-edges"
	// deadsetEdgesFile is the one name deadset reads, at its target root.
	deadsetEdgesFile = "deadset-edges.json"
	edgePrefix       = "wiregen/"
	// edgeBecause marks an edge wiregen wrote; one under edgePrefix without
	// it is hand-written, which a regeneration would otherwise delete.
	edgeBecause             = "generated by wiregen"
	defaultEdgesDescription = "Edges between Go wire symbols and the TypeScript wiregen generates from them; wiregen rewrites every edge under wiregen/."
)

// edge is one generated entry. json/v2 writes members in declaration order,
// so they are declared sorted, as the rest of the document's keys are.
type edge struct {
	Because  string `json:"because"`
	Provides string `json:"provides"`
	UsedBy   string `json:"used_by"`
}

// edgesDocument keeps every edge it read as raw JSON, so a hand-written edge
// is written back as it was, only re-indented. Description is a pointer so
// fieldalignment holds with the members declared in output order.
type edgesDocument struct {
	Description *string                   `json:"description,omitzero"`
	Edges       map[string]jsontext.Value `json:"edges"`
}

// renderDeadsetEdges merges the generated edges into the edges document
// files names, returning its new content.
func (g *generator) renderDeadsetEdges(engine *astEngine, files []genFile) (string, error) {
	i := slices.IndexFunc(files, func(f genFile) bool { return f.role == roleDeadsetEdges })
	sc, err := g.newEdgeScope(engine, files[i].name)
	if err != nil {
		return "", err
	}
	doc, err := readEdgesDocument(files[i].name)
	if err != nil {
		return "", err
	}
	var hand []string
	for id, raw := range doc.Edges {
		if !strings.HasPrefix(id, edgePrefix) {
			continue
		}
		var e struct {
			Because *string `json:"because"`
		}
		if json.Unmarshal(raw, &e) != nil || e.Because == nil || *e.Because != edgeBecause {
			hand = append(hand, id)
			continue
		}
		delete(doc.Edges, id)
	}
	if len(hand) > 0 {
		slices.Sort(hand)
		return "", fmt.Errorf("wiregen: %s holds hand-written edges under the %q prefix wiregen owns: %s; rename each outside it", files[i].name, edgePrefix, strings.Join(hand, ", "))
	}
	for id, e := range g.generatedEdges(engine, sc) {
		raw, encErr := json.Marshal(e)
		if encErr != nil {
			return "", fmt.Errorf("wiregen: encode edge %s: %w", id, encErr)
		}
		doc.Edges[id] = raw
	}
	out, err := json.Marshal(doc, json.Deterministic(true), jsontext.WithIndent("  "))
	if err != nil {
		return "", fmt.Errorf("wiregen: encode %s: %w", files[i].name, err)
	}
	return string(out) + "\n", nil
}

// readEdgesDocument reads the edges document at name. It refuses a file that
// is not regular, is not strict JSON, holds a member besides description and
// edges, or whose description is neither a string nor null; a null
// description is dropped and a null or absent edges reads as none. deadset
// validates the edges themselves. An absent file reads as a new document.
// No size limit applies, so Generate always reads back its own output.
func readEdgesDocument(name string) (edgesDocument, error) {
	description := defaultEdgesDescription
	fresh := edgesDocument{Description: &description, Edges: map[string]jsontext.Value{}}
	f, err := os.Open(name)
	if errors.Is(err, fs.ErrNotExist) {
		return fresh, nil
	}
	if err != nil {
		return edgesDocument{}, fmt.Errorf("wiregen: read %s: %w", name, err)
	}
	defer f.Close()
	if fi, statErr := f.Stat(); statErr != nil || !fi.Mode().IsRegular() {
		return edgesDocument{}, fmt.Errorf("wiregen: %s is not a regular file", name)
	}
	data, err := io.ReadAll(f)
	if err != nil {
		return edgesDocument{}, fmt.Errorf("wiregen: read %s: %w", name, err)
	}
	var doc edgesDocument
	if err := json.Unmarshal(data, &doc, json.RejectUnknownMembers(true)); err != nil {
		return edgesDocument{}, fmt.Errorf("wiregen: %s is not a deadset edges document: %w", name, err)
	}
	if doc.Edges == nil {
		doc.Edges = map[string]jsontext.Value{}
	}
	return doc, nil
}

// edgeScope places the generated files and the registered packages relative
// to deadset's target root.
type edgeScope struct {
	pkgDirs     map[string]string
	inside      map[string]bool
	root, tsDir string // resolved, absolute
}

func (g *generator) newEdgeScope(engine *astEngine, edgesFile string) (*edgeScope, error) {
	root, err := resolvedPath(g.o.deadsetRoot)
	if err != nil {
		return nil, fmt.Errorf("wiregen: the deadset target root %q: %w", g.o.deadsetRoot, err)
	}
	// edgesFile is the output path with its symlinks resolved, so it differs
	// only when deadset-edges.json itself is a link.
	if want := filepath.Join(root, deadsetEdgesFile); edgesFile != want {
		return nil, fmt.Errorf("wiregen: %s is a symbolic link to %s; deadset reads it as a regular file, so replace the link with the file", want, edgesFile)
	}
	tsDir, err := resolvedPath(g.o.tsDir)
	if err != nil {
		return nil, fmt.Errorf("wiregen: the TS directory %q: %w", g.o.tsDir, err)
	}
	if _, ok := below(root, tsDir); !ok {
		return nil, fmt.Errorf("wiregen: the TS directory %s is outside the deadset target root %s, which deadset reads TypeScript below", tsDir, root)
	}
	sc := &edgeScope{root: root, tsDir: tsDir, pkgDirs: map[string]string{}, inside: map[string]bool{}}
	for p, pkg := range engine.pkgs {
		if len(pkg.GoFiles) > 0 {
			sc.pkgDirs[p] = filepath.Dir(pkg.GoFiles[0])
		}
	}
	return sc, nil
}

// resolvedPath is p made absolute with the symlinks of its existing part
// resolved, as the operating system would open it.
func resolvedPath(p string) (string, error) {
	abs, err := workingDirPath(p)
	if err != nil {
		return "", err
	}
	t, err := locate(abs)
	if err != nil {
		return "", err
	}
	return t.path, nil
}

// below returns p's slash-separated path below root, "." for root itself.
func below(root, p string) (string, bool) {
	rel, err := filepath.Rel(root, p)
	if err != nil || !filepath.IsLocal(rel) {
		return "", false
	}
	return filepath.ToSlash(rel), true
}

// hasPackage reports whether deadset enumerates pkgPath: only a package whose
// files sit below the root, as deadset reports any other edge side absent.
func (sc *edgeScope) hasPackage(pkgPath string) bool {
	in, ok := sc.inside[pkgPath]
	if !ok {
		if dir, err := filepath.EvalSymlinks(sc.pkgDirs[pkgPath]); err == nil {
			_, in = below(sc.root, dir)
		}
		sc.inside[pkgPath] = in
	}
	return in
}

// module is the ts:// scope of name, a file inside the TS directory: the
// nearest package.json naming a package at or above it up to the root, else
// "." and the path from the root (deadset-spec contract/grammar/symbol-ref.md,
// "The TypeScript scope").
func (sc *edgeScope) module(name string) string {
	rel, _ := below(sc.root, filepath.Join(sc.tsDir, name)) // the TS directory is below the root
	for dir := path.Dir(rel); ; dir = path.Dir(dir) {
		if pkg := manifestName(filepath.Join(sc.root, filepath.FromSlash(dir))); pkg != "" {
			return "ts://" + packageScope(pkg) + "/" + pathScope(strings.TrimPrefix(rel, dir+"/"))
		}
		if dir == "." {
			return "ts://./" + pathScope(rel)
		}
	}
}

// packageScope percent-encodes each byte of an npm package name outside
// ASCII letters, digits, '.', '_' and '-', keeping a scoped name's '@' and
// '/', as deadset-spec's TS_PACKAGE spells it.
func packageScope(name string) string {
	keep := func(c byte) bool {
		return 'a' <= c && c <= 'z' || 'A' <= c && c <= 'Z' || '0' <= c && c <= '9' || c == '.' || c == '_' || c == '-'
	}
	if scope, rest, ok := strings.Cut(name, "/"); ok && strings.HasPrefix(scope, "@") {
		return "@" + percentEncode(scope[1:], keep) + "/" + percentEncode(rest, keep)
	}
	return percentEncode(name, keep)
}

// pathScope percent-encodes each byte of a slash-separated path's segments a
// scope holds no raw form of: a control, a space, '#', which ends the scope,
// and '%', which starts an encoding.
func pathScope(rel string) string {
	segs := strings.Split(rel, "/")
	for i, seg := range segs {
		segs[i] = percentEncode(seg, func(c byte) bool { return c > ' ' && c != 0x7F && c != '#' && c != '%' })
	}
	return strings.Join(segs, "/")
}

// percentEncode writes each byte of s keep refuses as '%' and two uppercase
// hex digits (RFC 3986, section 2.1).
func percentEncode(s string, keep func(byte) bool) string {
	var b strings.Builder
	for i := range len(s) {
		if keep(s[i]) {
			b.WriteByte(s[i])
		} else {
			fmt.Fprintf(&b, "%%%02X", s[i])
		}
	}
	return b.String()
}

// manifestName is the package name dir's package.json declares, or "" when
// it has none, is unreadable or does not parse, as deadset-ts reads it.
func manifestName(dir string) string {
	data, err := os.ReadFile(filepath.Join(dir, "package.json"))
	if err != nil {
		return ""
	}
	var m struct {
		Name jsontext.Value `json:"name"`
	}
	var name string
	if json.Unmarshal(data, &m, jsontext.AllowDuplicateNames(true), jsontext.AllowInvalidUTF8(true)) != nil ||
		json.Unmarshal(m.Name, &name) != nil {
		return ""
	}
	return name
}

// edgeSet collects edges by identifier, keeping only those whose Go package
// deadset enumerates.
type edgeSet struct {
	sc  *edgeScope
	out map[string]edge
}

func (s edgeSet) add(id, goPkg, goSym, ts string) {
	if s.sc.hasPackage(goPkg) {
		s.out[edgePrefix+id] = edge{Because: edgeBecause, Provides: "go://" + goPkg + "#" + goSym, UsedBy: ts}
	}
}

// generatedEdges lists the edges of every symbol wiregen generates TS from
// whose package deadset enumerates, by identifier.
func (g *generator) generatedEdges(engine *astEngine, sc *edgeScope) map[string]edge {
	s := edgeSet{sc: sc, out: map[string]edge{}}
	typesMod := sc.module(g.o.typesFilename) + "#"
	g.typeEdges(engine, s, typesMod)
	g.enumEdges(engine, s, typesMod)
	return s.out
}

// typeEdges adds each registered type's edge and its fields'.
func (g *generator) typeEdges(engine *astEngine, s edgeSet, typesMod string) {
	for _, ti := range engine.types {
		tn := typesMod + g.tsName(ti.Name)
		s.add(edgeSegment(ti.Name), g.typeNames[ti.Name], ti.Name, tn)
		for _, em := range ti.Embeds {
			s.member(ti, em.Owner, em.GoName, tn)
		}
		switch {
		case ti.Map != nil:
		case ti.Union != nil:
			s.unionFields(ti, tn)
		default:
			for i := range ti.Fields {
				s.field(ti, &ti.Fields[i], tn, true)
			}
		}
	}
}

// unionFields adds the edges of the fields ti's cases emit. deadset-ts
// (src/inventory/syntax.ts, aliasMembers) makes a property one case alone
// declares a member of the alias, and names none that two cases declare, so
// such a field pairs with the alias itself.
func (s edgeSet) unionFields(ti *typeInfo, alias string) {
	declaring := map[string]int{}
	for i := range ti.Union.cases {
		for _, f := range ti.caseFields(&ti.Union.cases[i]) {
			declaring[f.WireName]++
		}
	}
	for name, n := range declaring {
		s.field(ti, ti.field(name), alias, n == 1)
	}
}

// field adds the edge of ti's field f, paired with the TS type ts or, when
// member, with f's property in it.
func (s edgeSet) field(ti *typeInfo, f *fieldInfo, ts string, member bool) {
	if member {
		ts += "." + tsComponent(f.WireName)
	}
	s.member(ti, f.Owner, f.GoName, ts)
}

// member adds the edge of the struct member goName selects from ti, declared
// by owner, unless an unnamed struct declares it, which no reference names.
func (s edgeSet) member(ti *typeInfo, owner *Type, goName, ts string) {
	if owner.Name == "" {
		return
	}
	own := goName[strings.LastIndex(goName, ".")+1:]
	s.add(edgeSegment(ti.Name)+"/"+edgeSegment(goName), owner.PkgPath, owner.Name+"."+own, ts)
}

// enumEdges adds each enum's edge and its constants': a constant pairs with
// the decoders' member list when emitted, else with the enum's alias.
func (g *generator) enumEdges(engine *astEngine, s edgeSet, typesMod string) {
	decoders := s.sc.module(g.o.decodersFilename) + "#"
	_, used := g.decoderBodies(engine)
	for _, name := range enumNamesSlice(g.enums) {
		def := g.enums[name]
		alias := typesMod + g.tsEnumName(name)
		s.add(edgeSegment(name), def.pkgPath, name, alias)
		member := alias
		if g.emitsEnumConst(used, name) {
			member = decoders + g.enumConstName(name)
		}
		for _, c := range def.consts {
			s.add(edgeSegment(name)+"/"+edgeSegment(c), def.pkgPath, c, member)
		}
	}
}

// edgeSegment spells a Go name in an edge identifier's character set,
// ASCII letters, digits, '_' and '.': any other rune becomes "-u" and six hex
// digits, and '-' is in no Go name, so two names never share a spelling.
func edgeSegment(goName string) string {
	var b strings.Builder
	for _, r := range goName {
		if r <= unicode.MaxASCII && (r == '_' || r == '.' || unicode.IsLetter(r) || unicode.IsDigit(r)) {
			b.WriteRune(r)
		} else {
			fmt.Fprintf(&b, "-u%06X", r)
		}
	}
	return b.String()
}

// tsComponent spells a wire name as a ts:// fragment component the way
// deadset-ts src/ref.ts nameComponent does: bare when it matches TS_IDENT or
// '#' and TS_IDENT, else single-quoted. isValidJSONName admits none of the
// ' \ CR and LF a quoted component escapes.
func tsComponent(name string) string {
	if isTSIdent(strings.TrimPrefix(name, "#")) {
		return name
	}
	return "'" + name + "'"
}

// isTSIdent is deadset-ts's TS_IDENT: an ASCII letter, '_', '$' or non-ASCII
// rune, then any of those or an ASCII digit.
func isTSIdent(s string) bool {
	if s == "" {
		return false
	}
	for i, r := range s {
		ok := r == '_' || r == '$' || r > unicode.MaxASCII || 'a' <= r && r <= 'z' || 'A' <= r && r <= 'Z' || i > 0 && '0' <= r && r <= '9'
		if !ok {
			return false
		}
	}
	return true
}
